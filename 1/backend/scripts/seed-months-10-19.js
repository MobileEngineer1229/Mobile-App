async function run() {
  // Deduplicate by (title, sub_category): min month, max done_count
  const map = new Map();
  for (const [month, title, sub_category, done_count] of RAW) {
    const key = `${title}|||${sub_category}`;
    const e = map.get(key);
    if (!e) {
      map.set(key, { month, title, sub_category, done_count });
    } else {
      if (month < e.month) e.month = month;
      if (done_count > e.done_count) e.done_count = done_count;
    }
  }

  const entries = [...map.values()];
  let inserted = 0, updated = 0;

  for (const { month, title, sub_category, done_count } of entries) {
    const category = CAT[sub_category] || 'cognitive';
    const res = await pool.query(`
      INSERT INTO activities (title, category, sub_category, month_min, month_max, language, done_count, doctor_verified, is_premium)
      VALUES ($1, $2, $3, $4, $4, 'en', $5, false, false)
      ON CONFLICT (title, sub_category) DO UPDATE SET
        month_min  = LEAST(EXCLUDED.month_min, activities.month_min),
        month_max  = GREATEST(EXCLUDED.month_max, activities.month_max),
        done_count = GREATEST(EXCLUDED.done_count, activities.done_count)
      RETURNING (xmax = 0) AS was_insert
    `, [title, category, sub_category, month, done_count]);
    if (res.rows[0].was_insert) inserted++; else updated++;
  }

  console.log(`Done. ${inserted} inserted, ${updated} updated (${entries.length} unique activities).`);
  await pool.end();
}

run().catch(e => { console.error(e.message); process.exit(1); });
