const map = new Map();
for (const r of RAW) {
  const key = `${r.title}||${r.sub_category}`;
  if (!map.has(key)) {
    map.set(key, { title: r.title, sub_category: r.sub_category, done_count: r.done_count, month_min: r.month, month_max: r.month });
  } else {
    const e = map.get(key);
    e.month_min = Math.min(e.month_min, r.month);
    e.month_max = Math.max(e.month_max, r.month);
    e.done_count = Math.max(e.done_count, r.done_count);
  }
}

const deduped = [...map.values()];

async function run() {
  const client = await pool.connect();
  try {
    let inserted = 0, updated = 0, skipped = 0;
    for (const r of deduped) {
      const category = CAT[r.sub_category];
      if (!category) {
        console.warn(`UNKNOWN sub_category: "${r.sub_category}" (title: "${r.title}") — skipping`);
        skipped++;
        continue;
      }
      const res = await client.query(`
        INSERT INTO activities (title, category, sub_category, month_min, month_max, done_count, doctor_verified)
        VALUES ($1, $2, $3, $4, $5, $6, false)
        ON CONFLICT (title, sub_category) DO UPDATE SET
          month_min  = LEAST(activities.month_min, EXCLUDED.month_min),
          month_max  = GREATEST(activities.month_max, EXCLUDED.month_max),
          done_count = GREATEST(activities.done_count, EXCLUDED.done_count)
        RETURNING (xmax = 0) AS inserted
      `, [r.title, category, r.sub_category, r.month_min, r.month_max, r.done_count]);
      if (res.rows[0].inserted) inserted++; else updated++;
    }
    console.log(`Done: ${inserted} inserted, ${updated} updated, ${skipped} skipped`);
  } finally {
    client.release();
    await pool.end();
  }
}

