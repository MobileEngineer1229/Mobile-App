    model_type: str = "bpe"

    # Letter inclusion ratio
    # 0.9995: 99 of the letters in the entire corpus.95% Set to be included in vocabulary
    character_coverage: float = 0.9995

    # storage path prefix
    # After training dprk_sp.model and dprk_sp.vocab File created
    output_prefix: str = "tokenizer/dprk_sp"


