@dataclass
class InferenceConfig:
    """Create post(inference) default settings.

    【Beginner's Guide】
      Gradio UIThis is the default value for the values adjusted with the slider..
      generate.pyWow chat.pyUse these values in.
    """

    # Maximum characters to generate once(tag) number
    default_max_new_tokens: int = 256

